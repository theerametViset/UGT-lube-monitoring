"""Write supabase/0032_real_equipment.sql from lib/demo-data.ts (sites, asset types, RAW_ASSETS).
Run from anywhere: python scripts/gen-real-equipment-sql.py"""
import io, re, json
import os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "")
src = io.open(ROOT + "lib/demo-data.ts", encoding="utf-8").read()

def arr(start):
    i = src.index(start); j = src.index("= [", i) + 2; k = src.index("];", j)
    return json.loads(re.sub(r",\s*\]$", "]", src[j:k + 1].strip()))

sites = arr("const sites: Site[] =")
types = arr("const types: AssetType[] =")
s0 = src.index("const RAW_ASSETS"); e = src.index("];", s0)
assets = [json.loads(m.group(0)) for m in re.finditer(r'\["[^\]]*\]', src[s0:e])]
assert len({a[0] for a in assets}) == len(assets)

def q(v):
    if v is None: return "null"
    if isinstance(v, (int, float)): return str(v)
    return "'" + str(v).replace("'", "''") + "'"

out = [f"""-- Migration 0032 — load the real UGT oil-lubricated machines. Run AFTER 0031.
--
-- Generated by scripts/gen-real-equipment-sql.py from lib/demo-data.ts (the list from "Final equipment in program.xlsx",
-- {len(assets)} machines) so Supabase shows the same machines as Demo Mode.
-- 1. Adds the real plants (CPL, TSL, UFA, UNT, UTCA) and the asset types they use.
-- 2. Inserts the machines that are not there yet — a machine already in the table
--    (maybe edited in the Asset DB since) is left as it is.
--    health/status are left to compute_health.
-- 3. Removes the prototype plants and types from 0002 that nothing uses.
-- Blank VG / oil quantity / cycles are 0, the same as Demo Mode (VG 0 = no VG grade:
-- viscosity is checked against the generic alarm_params limits, 242 / 264 cSt by default).
-- Safe to re-run: nothing edited later is overwritten.

insert into public.sites (code, name, sort_order) values"""]
out.append(",\n".join(f"  ({q(s['code'])}, {q(s['name'])}, {q(s['sort_order'])})" for s in sites))
out.append("on conflict (code) do update set name = excluded.name, sort_order = excluded.sort_order;\n")
out.append("insert into public.asset_types (name, abbr, color) values")
out.append(",\n".join(f"  ({q(t['name'])}, {q(t.get('abbr'))}, {q(t.get('color'))})" for t in types))
out.append("on conflict (name) do update set abbr = excluded.abbr, color = excluded.color;\n")
out.append("insert into public.assets (id, name, type, site, install_date, motor_kw, rpm, vg_grade, oil_brand,\n"
           "  oil_qty_l, oil_change_months, oil_sample_months, last_update) values")
out.append(",\n".join("  (" + ", ".join(q(v) for v in a) + ")" for a in assets))
out.append("""on conflict (id) do nothing;
""")
real_types = ", ".join(q(t["name"]) for t in types)
out.append(f"""-- Prototype plants / types from 0002 — only these, and only while nothing (e.g. budget
-- rows) still points at them. Real types with no machine yet stay for later imports.
do $$
declare r record;
begin
  for r in select s.code from public.sites s
           where code in ('UT', 'PCD', 'SA', 'NY1')
             and not exists (select 1 from public.assets a where a.site = s.code) loop
    begin delete from public.sites where code = r.code;
    exception when foreign_key_violation then null; end;
  end loop;
  delete from public.asset_types t
    where t.name not in ({real_types})
      and not exists (select 1 from public.assets a where a.type = t.name);
end $$;

select public.recompute_all_health();
""")
io.open(ROOT + "supabase/0032_real_equipment.sql", "w", encoding="utf-8", newline="\n").write("\n".join(out))
print(len(sites), "sites", len(types), "types", len(assets), "assets")
